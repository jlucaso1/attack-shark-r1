/// Converts a DPI value (100..=18000, divisible by 100) to its protocol byte code.
pub fn dpi_to_byte(dpi: u32) -> Result<u8, DriverError> {
    if !(100..=18000).contains(&dpi) || dpi % 100 != 0 {
        return Err(DriverError::InvalidDpi(dpi));
    }
    let index = (dpi / 100 - 1) as usize;
    Ok(DPI_LOOKUP_TABLE[index])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_valid_dpis() {
        assert_eq!(dpi_to_byte(100).unwrap(), 0x02);
        assert_eq!(dpi_to_byte(800).unwrap(), 0x12);
        assert_eq!(dpi_to_byte(1600).unwrap(), 0x25);
        assert_eq!(dpi_to_byte(10000).unwrap(), 0xeb);
        assert_eq!(dpi_to_byte(10100).unwrap(), 0x76);
        assert_eq!(dpi_to_byte(18000).unwrap(), 0xd3);
    }

    #[test]
    fn test_invalid_dpis() {
        assert!(dpi_to_byte(50).is_err());
        assert!(dpi_to_byte(850).is_err());
        assert!(dpi_to_byte(18100).is_err());
    }
}
